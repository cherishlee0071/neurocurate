"""Approved, offline real EEG/vision smoke test using retained verified files."""
import argparse
from dataclasses import asdict
from datetime import datetime, timezone
import gc
import json
from pathlib import Path
import shutil

import numpy as np
import yaml
from neurocurate.acquisition import verify_artifact
from neurocurate.eeg import EEGConfig, load_eeg, extract_eeg_features
from neurocurate.metadata import align_features
from neurocurate.rdm import compute_rdm, validate_rdm
from neurocurate.realdata import load_real_manifest
from neurocurate.lowdisk import sha256
from neurocurate.vision import extract_vision_features, save_feature_cache, load_feature_cache


def save(path, data):
    path.write_text(json.dumps(data, indent=2) + "\n")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--config", type=Path, default=Path("configs/real_subset.yaml"))
    parser.add_argument("--audit", type=Path, default=Path("results/phase1/real_data_audit.json"))
    parser.add_argument("--trust-official-pickle", action="store_true")
    args = parser.parse_args()
    if not args.trust_official_pickle:
        parser.error("explicit approval is required; use --trust-official-pickle only after approval")
    config = yaml.safe_load(args.config.read_text())
    output = Path(config["output_dir"])
    if output.exists():
        raise FileExistsError("preserve existing smoke outputs; select a new output_dir")
    if shutil.disk_usage(output.parent).free < 256 * 1024**2:
        raise ValueError("insufficient output headroom")
    acquisition = json.loads(Path(config["acquisition_manifest"]).read_text())
    for artifact in acquisition["files"] + acquisition["extracted"]:
        verify_artifact(artifact)
    eeg_artifact = next(a for a in acquisition["extracted"] if a["archive"] == "sub-01.zip")
    metadata_artifact = next(a for a in acquisition["files"] if Path(a["path"]).name == "image_metadata.npy")
    audit_path = args.audit
    audit = json.loads(audit_path.read_text())
    def checkpoint(status):
        audit["status"] = status
        audit["continued_at_utc"] = datetime.now(timezone.utc).isoformat()
        save(audit_path, audit)
    audit["approval"] = dict(explicit_user_approval=True, scope="two SHA256-verified official NPY files only")
    checkpoint("inspecting_approved_metadata")
    manifest, selected, alignment = load_real_manifest(metadata_artifact["path"],
        config["image_root"], trusted_pickle=True)
    # Preserve source evidence for the condition-ID -> EEG-axis convention.
    source = json.loads(Path("outputs/real-phase0-source/source_provenance.json").read_text())
    required_sources = {"get_stimuli_test.m", "data_collection_test.m", "source_to_raw.py", "preprocessing_utils.py"}
    if not required_sources <= {Path(item["path"]).name for item in source}:
        raise ValueError("incomplete numeric condition mapping source evidence")
    alignment["source_code_provenance"] = source
    for item in source:
        if sha256(item["path"]) != item["sha256"]:
            raise ValueError("mapping source provenance changed")
    audit["alignment"] = alignment
    audit["access"]["metadata_object_loaded"] = True
    checkpoint("exact_protocol_mapping_verified")
    ids = selected.image_id.to_numpy(dtype=str)
    trials = load_eeg(eeg_artifact["path"], "sanity", ids, trusted_pickle=True, manifest=manifest)
    dt = np.diff(trials.times)
    if not np.allclose(dt, dt[0], atol=1e-12, rtol=0):
        raise ValueError("nonuniform real EEG time axis")
    if len(trials.data) % 200 != 0:
        raise ValueError("inconsistent repetition count")
    shape = dict(released_tensor_shape=[200, len(trials.data) // 200, len(trials.channel_names), len(trials.times)],
        released_tensor_axes=["images", "repetitions", "channels", "time"],
        loader_trial_shape=list(trials.data.shape), dtype=str(trials.data.dtype),
        sampling_rate_hz=float(1 / dt[0]), channel_count=len(trials.channel_names),
        channel_names=trials.channel_names.tolist(), trial_count=len(trials.data),
        image_count=200, repetitions_per_image=len(trials.data) // 200,
        first_time_seconds=float(trials.times[0]), last_time_seconds=float(trials.times[-1]),
        finite_eeg=bool(np.isfinite(trials.data).all()),
        per_trial_ids="generated by image-axis/repetition expansion using validated numeric condition mapping",
        original_split="test", repository_split="sanity", subject="sub-01")
    audit.update(eeg_tensor_shape=shape["released_tensor_shape"], eeg_dtype=shape["dtype"],
                 sampling_rate_hz=shape["sampling_rate_hz"], channel_count=shape["channel_count"],
                 trial_count=shape["trial_count"], image_axis_count=200, eeg_shape_report=shape)
    audit["access"]["eeg_tensor_loaded"] = True
    checkpoint("real_eeg_loaded")
    preprocessing = EEGConfig(**config["preprocessing"])
    feature_ids, features, repetitions = extract_eeg_features(trials, preprocessing)
    features = align_features(ids, feature_ids, features)
    full_rdm = validate_rdm(compute_rdm(features, config["brain_metric"]))
    subset = config["subset_eeg_indices"]
    if len(subset) < 3 or len(set(subset)) != len(subset) or any(type(i) is not int or not 0 <= i < 200 for i in subset):
        raise ValueError("invalid explicit subset EEG indices")
    subset_ids = ids[subset]
    subset_features = features[subset]
    small_rdm = validate_rdm(compute_rdm(subset_features, config["brain_metric"]))
    if not np.allclose(small_rdm, full_rdm[np.ix_(subset, subset)], atol=1e-12):
        raise ValueError("subset RDM differs from full RDM restriction")
    output.mkdir()
    manifest.to_csv(output / "all_split_metadata_manifest.csv", index=False)
    selected.to_csv(output / "test_image_mapping.csv", index=False)
    np.save(output / "all_image_ids.npy", ids, allow_pickle=False)
    np.save(output / "eeg_features_200.npy", features, allow_pickle=False)
    np.save(output / "brain_rdm_200.npy", full_rdm, allow_pickle=False)
    np.save(output / "image_ids.npy", subset_ids, allow_pickle=False)
    np.save(output / "eeg_features.npy", subset_features, allow_pickle=False)
    np.save(output / "brain_rdm.npy", small_rdm, allow_pickle=False)
    save(output / "eeg_shape_report.json", shape)
    save(output / "image_alignment_report.json", alignment)
    (output / "config.yaml").write_text(yaml.safe_dump(config))
    audit["brain_rdm"] = dict(status="verified", full_shape=list(full_rdm.shape),
        subset_shape=list(small_rdm.shape), feature_shape=list(features.shape),
        subset_feature_shape=list(subset_features.shape), metric=config["brain_metric"],
        symmetric=True, finite=True, diagonal_zero=True, image_order_verified=True)
    audit["real_data_operations"].extend(["loaded two explicitly approved official NPY objects",
        "validated numeric condition metadata and all 200 image mappings",
        "loaded actual EEG through repository loader", "averaged 80 repetitions/image using repository preprocessing",
        "computed full 200-image and small-subset real EEG RDMs"])
    audit["blockers"] = []
    checkpoint("real_brain_rdms_verified")
    print(json.dumps(shape, indent=2), flush=True)
    print("EEG features", features.shape, "subset", subset_features.shape, flush=True)
    del trials
    gc.collect()
    for name, options in config["vision"].items():
        paths = selected.iloc[subset].image_path.tolist()
        embeddings, provenance = extract_vision_features(subset_ids, paths, kind=name, **options)
        save_feature_cache(output / f"{name}_features.npz", subset_ids, embeddings,
                           split="sanity", model_name=name, provenance=provenance)
        cached_ids, cached_features, _ = load_feature_cache(output / f"{name}_features.npz",
                                                            split="sanity", model_name=name)
        if not np.array_equal(cached_ids, subset_ids) or not np.allclose(cached_features, embeddings):
            raise ValueError("vision cache roundtrip failed")
        rdm = validate_rdm(compute_rdm(embeddings, config["vision_metric"]))
        np.save(output / f"{name}_rdm.npy", rdm, allow_pickle=False)
        audit["vision"][name] = dict(status="verified_real_subset", feature_shape=list(embeddings.shape),
                                     rdm_shape=list(rdm.shape), metric=config["vision_metric"], provenance=provenance)
        checkpoint(name + "_real_features_verified")
        print(name, embeddings.shape, "real-image features verified", flush=True)
        gc.collect()
    # Reload every numeric result safely and independently recompute distances.
    saved_ids = np.load(output / "image_ids.npy", allow_pickle=False)
    if not np.array_equal(saved_ids, subset_ids):
        raise ValueError("saved image ordering failed")
    for suffix in ["", "_200"]:
        saved = np.load(output / ("eeg_features" + suffix + ".npy"), allow_pickle=False)
        saved_rdm = validate_rdm(np.load(output / ("brain_rdm" + suffix + ".npy"), allow_pickle=False))
        if not np.allclose(saved_rdm, compute_rdm(saved, config["brain_metric"]), atol=1e-12):
            raise ValueError("saved Brain RDM independent recomputation failed")
    for name in config["vision"]:
        _, saved, _ = load_feature_cache(output / f"{name}_features.npz", split="sanity", model_name=name)
        saved_rdm = validate_rdm(np.load(output / f"{name}_rdm.npy", allow_pickle=False))
        if not np.allclose(saved_rdm, compute_rdm(saved, config["vision_metric"]), atol=1e-12):
            raise ValueError("saved vision RDM independent recomputation failed")
    provenance = dict(subject="sub-01", split="sanity", acquisition_manifest=config["acquisition_manifest"],
        original_split="test", eeg_export_sha256=eeg_artifact["sha256"],
        metadata_sha256=metadata_artifact["sha256"], preprocessing=asdict(preprocessing),
        shared_whitening_limitation="official MVNN uses both training/test partitions and all repetitions",
        reliability="not estimated in this small integration audit", training_performed=False,
        output_sha256={p.name: sha256(p) for p in output.iterdir() if p.is_file()})
    save(output / "provenance.json", provenance)
    audit["output_dir"] = str(output.resolve())
    audit["output_verification"] = dict(all_saved_brain_rdms_recomputed=True, safe_numeric_reload=True)
    audit["limitations"] = ["Single subject; no cross-subject conclusion or reliability estimate.",
        "Official session whitening uses training and test repetitions; held-out training preprocessing independence is not established.",
        "Raw per-trial events and original session IDs were not independently roundtripped.",
        "Train/test metadata identities are disjoint; training image content hashes were not checked."]
    audit["next_experiment"] = "Estimate repeated-image RDM split-half reliability with label-permutation controls, conditional on supplied whitening; then compare a second subject."
    checkpoint("PASS_REAL_INTEGRATION")
    audit_path.with_suffix(".md").write_text("\n".join([
        "# Phase 1 real-data integration", "", "Status: PASS_REAL_INTEGRATION", "",
        "The user explicitly approved loading the two SHA256-verified official NPY files.",
        "Reused real subject-01 test EEG and 200 original test images. No additional EEG/image/model downloads.",
        "EEG: float64 (200,80,17,100); loader (16000,17,100); 100 Hz, -0.2 to 0.79 seconds.",
        "All 200 test image identities align through ordered numeric condition metadata and the pinned author protocol.",
        "No file-order inference, synthetic substitution or training/evaluation split mixing was performed.",
        "Existing preprocessing: 100 <= t < 500 ms, no extra baseline, average 80 repetitions per image.",
        f"Real EEG features: {features.shape}; Brain RDMs: {full_rdm.shape} and subset {small_rdm.shape}.",
        f"Real DINOv2/CLIP features and cosine RDMs computed for {len(subset)} matching images, local pinned checkpoints only.",
        "Saved Brain/vision distances were independently recomputed from safely reloaded features.", "",
        "Limits: one subject, no reliability estimate or cross-subject consensus; official MVNN shares training/test covariance.",
        "Raw per-trial event and session labels were not independently recovered; train-image pixel hashes were not checked.",
        "Next: split-half RDM reliability and image-label permutation controls, followed by a second subject.", ""]))
    (output / "COMPLETE").write_text("real input alignment, EEG RDMs and subset vision embeddings verified\n")


if __name__ == "__main__":
    main()
